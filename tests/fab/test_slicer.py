def test_parse_gcode_stats():
    prusa = "\n".join([
        "; generated by PrusaSlicer 2.8.1+MacOS-arm64 on 2026-10-04 at 10:00:00 UTC",
        "G1 X10 Y10",
        "; filament used [mm] = 4123.45",
        "; filament used [cm3] = 9.92",
        "; filament used [g] = 12.00",
        "; filament cost = 0.99",
        "; total filament used [g] = 12.34",
        "; total filament cost = 0.99",
        "; estimated printing time (normal mode) = 1h 2m 3s",
        "; estimated first layer printing time (normal mode) = 1m 5s",
    ])
    s = parse_gcode_stats(prusa)
    assert s["time_s"] == 3723
    assert s["filament_g"] == pytest.approx(12.34)  # the total wins over the per-extruder line
    assert s["filament_m"] == pytest.approx(4.12345)
    assert s["filament_cm3"] == pytest.approx(9.92)
    assert s["cost"] == pytest.approx(0.99)
    assert s["generator"].startswith("PrusaSlicer 2.8.1")

    assert parse_gcode_stats("; filament used [g] = 12.34\n")["filament_g"] == pytest.approx(12.34)
    orca = parse_gcode_stats("; HEADER_BLOCK_START\n; model printing time: 1h 2m 3s\n")
    assert orca["time_s"] == 3723 and orca["model_time_s"] == 3723


def test_parse_gcode_stats_variants():
    both = parse_gcode_stats("; model printing time: 1h 2m 3s; total estimated time: 1h 10m 0s\r\n")
    assert both["time_s"] == 4200 and both["model_time_s"] == 3723
    multi = parse_gcode_stats(
        "; filament used [g] = 1.5, 2.5\n; filament used [mm] = 100.0, 300.0\n"
        "; estimated printing time (normal mode) = 1d 0h 0m 1s\n"
    )
    assert multi["filament_g"] == pytest.approx(4.0) and multi["filament_m"] == pytest.approx(0.4)
    assert multi["time_s"] == 86401
    bambu = parse_gcode_stats("; total filament length [mm] : 2500.0\n; total filament weight [g] : 7.5\n")
    assert bambu["filament_m"] == pytest.approx(2.5) and bambu["filament_g"] == pytest.approx(7.5)
    empty = parse_gcode_stats("G28\nG1 X0\n")
    assert empty["time_s"] is None and empty["filament_g"] is None and empty["filament_m"] is None
