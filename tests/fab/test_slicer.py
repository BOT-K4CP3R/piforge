# Stand-in for the PrusaSlicer CLI: answers --help with a version banner, otherwise records its
# argv (one per line) next to itself and writes a small G-code file to --output.
FAKE_PRUSA = r"""#!/bin/sh
here="${0%/*}"  # no external commands: PATH holds only this folder
out=""
case "$1" in --help) echo "PrusaSlicer-2.8.1+MacOS-arm64 based on Slic3r"; exit 0 ;; esac
printf '%s\n' "$@" > "$here/argv.txt"
while [ $# -gt 0 ]; do
  case "$1" in --output) out="$2"; shift ;; esac
  shift
done
printf '; generated by PrusaSlicer 2.8.1\nG1 X0\n; filament used [mm] = 1234.5\n; total filament used [g] = 3.70\n; estimated printing time (normal mode) = 12m 3s\n' > "$out"
echo "Slicing result exported to $out"
"""

# Stand-in for the OrcaSlicer / Bambu Studio CLI: writes plate_1.gcode into --outputdir.
FAKE_ORCA = r"""#!/bin/sh
here="${0%/*}"  # no external commands: PATH holds only this folder
outdir=""
case "$1" in --help) echo "OrcaSlicer-2.2.0 command line"; exit 0 ;; esac
printf '%s\n' "$@" > "$here/argv.txt"
while [ $# -gt 0 ]; do
  case "$1" in --outputdir) outdir="$2"; shift ;; esac
  shift
done
printf '; HEADER_BLOCK_START\n; model printing time: 20m 0s; total estimated time: 25m 0s\n; total filament length [mm] : 2000.0\n; total filament weight [g] : 6.10\n; HEADER_BLOCK_END\nG1 X0\n' > "$outdir/plate_1.gcode"
"""

FAKE_BROKEN = r"""#!/bin/sh
case "$1" in --help) echo "PrusaSlicer-2.8.1"; exit 0 ;; esac
echo "error: object is not manifold" >&2
exit 3
"""

FAKE_SILENT = r"""#!/bin/sh
case "$1" in --help) echo "PrusaSlicer-2.8.1"; exit 0 ;; esac
exit 0
"""

FAKE_ORCA_SILENT = r"""#!/bin/sh
case "$1" in --help) echo "OrcaSlicer-2.2.0"; exit 0 ;; esac
exit 0
"""


def _install(directory: Path, name: str, script: str) -> Path:
    directory.mkdir(parents=True, exist_ok=True)
    exe = directory / name
    exe.write_text(script)
    exe.chmod(0o755)
    return exe


@pytest.fixture
def no_slicers(monkeypatch, tmp_path):
    """Hide every real slicer: empty PATH, no app folders, no PIFORGE_SLICER override."""
    empty = tmp_path / "empty-bin"
    empty.mkdir()
    monkeypatch.setenv("PATH", str(empty))
    monkeypatch.delenv("PIFORGE_SLICER", raising=False)
    monkeypatch.setattr(slicer, "APP_DIRS", (tmp_path / "no-apps",))
    return empty


@pytest.fixture
def stl(spaced_tmp):
    path = spaced_tmp / "my part.stl"
    path.write_text("solid part\nendsolid part\n")
    return path


def test_slicer_absent(no_slicers, stl, spaced_tmp):
    assert find_slicer() is None
    with pytest.raises(SlicerNotFoundError) as excinfo:
        slice_stl(stl, "generic", "PLA", spaced_tmp / "out")
    assert isinstance(excinfo.value, ToolNotFoundError)
    assert isinstance(excinfo.value, PiForgeError)
    assert "PrusaSlicer" in str(excinfo.value)


def test_find_slicer_on_path(no_slicers, monkeypatch, spaced_tmp):
    exe = _install(spaced_tmp / "bin", "prusa-slicer", FAKE_PRUSA)
    monkeypatch.setenv("PATH", str(exe.parent))
    info = find_slicer()
    assert isinstance(info, SlicerInfo)
    assert (info.name, Path(info.path), info.version) == ("PrusaSlicer", exe, "2.8.1")


def test_find_slicer_in_applications(no_slicers, monkeypatch, spaced_tmp):
    apps = spaced_tmp / "Applications"
    bundle = apps / "OrcaSlicer.app" / "Contents"
    exe = _install(bundle / "MacOS", "OrcaSlicer", FAKE_ORCA)
    (bundle / "Info.plist").write_bytes(plistlib.dumps({"CFBundleShortVersionString": "2.2.0"}))
    monkeypatch.setattr(slicer, "APP_DIRS", (apps,))
    info = find_slicer()
    assert (info.name, Path(info.path), info.version) == ("OrcaSlicer", exe, "2.2.0")


def test_slice_stl_with_prusa_cli(no_slicers, monkeypatch, spaced_tmp, stl):
    exe = _install(spaced_tmp / "bin", "prusa-slicer", FAKE_PRUSA)
    monkeypatch.setenv("PATH", str(exe.parent))
    out_dir = spaced_tmp / "out dir"
    res = slice_stl(stl, "prusa_mk4", "PETG", out_dir, infill=0.2, supports=True)
    assert isinstance(res, SliceResult)
    assert res.gcode_path == out_dir / "my part.gcode" and res.gcode_path.is_file()
    assert res.time_s == 723 and res.filament_g == pytest.approx(3.70)
    assert res.filament_m == pytest.approx(1.2345)
    assert res.settings_applied
    assert "exported" in res.log
    argv = (exe.parent / "argv.txt").read_text().splitlines()
    assert argv[-1] == str(stl) and "--export-gcode" in argv

    def opt(name):
        return argv[argv.index(name) + 1]

    assert opt("--output") == str(out_dir / "my part.gcode")
    assert opt("--fill-density") == "20%"
    assert opt("--bed-shape") == "0x0,250x0,250x210,0x210"  # prusa_mk4 bed
    assert opt("--max-print-height") == "220"
    assert opt("--layer-height") == "0.2" and opt("--nozzle-diameter") == "0.4"
    assert opt("--filament-density") == "1.27"  # PETG
    assert "--support-material" in argv


