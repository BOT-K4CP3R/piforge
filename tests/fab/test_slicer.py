def test_slice_stl_with_orca_cli_via_env(no_slicers, monkeypatch, spaced_tmp, stl, caplog):
    exe = _install(spaced_tmp / "tools", "orca-slicer", FAKE_ORCA)
    monkeypatch.setenv("PIFORGE_SLICER", str(exe))
    assert find_slicer().name == "OrcaSlicer"
    out_dir = spaced_tmp / "orca out"
    with caplog.at_level(logging.WARNING, logger="piforge.fab.slicer"):
        res = slice_stl(stl, "bambu_p1s", "PLA", out_dir)
    # Orca/Bambu CLIs take no per-option overrides: the stats describe the slicer's own profile
    assert res.settings_applied is False
    assert any("not applied" in r.getMessage() for r in caplog.records if r.levelno == logging.WARNING)
    assert res.gcode_path == out_dir / "plate_1.gcode"
    assert res.time_s == 25 * 60 and res.filament_g == pytest.approx(6.10)
    assert res.filament_m == pytest.approx(2.0)
    argv = (exe.parent / "argv.txt").read_text().splitlines()
    assert argv[:2] == ["--slice", "0"] and argv[argv.index("--outputdir") + 1] == str(out_dir)
    assert argv[-1] == str(stl)


@pytest.mark.parametrize("kwargs", [{"infill": 0.4}, {"supports": True}])
def test_orca_rejects_settings_it_cannot_apply(no_slicers, monkeypatch, spaced_tmp, stl, kwargs):
    monkeypatch.setenv("PIFORGE_SLICER", str(_install(spaced_tmp / "tools", "orca-slicer", FAKE_ORCA)))
    with pytest.raises(PiForgeError, match="--load-settings"):
        slice_stl(stl, "bambu_p1s", "PLA", spaced_tmp / "out", **kwargs)


def test_orca_filament_profile_alone_cannot_carry_infill(no_slicers, monkeypatch, spaced_tmp, stl):
    # infill and supports live in the process profile (--load-settings); a filament file has neither
    monkeypatch.setenv("PIFORGE_SLICER", str(_install(spaced_tmp / "tools", "orca-slicer", FAKE_ORCA)))
    with pytest.raises(PiForgeError, match="--load-settings"):
        slice_stl(stl, "bambu_p1s", "PLA", spaced_tmp / "out", infill=0.4,
                  extra_args=["--load-filaments", "pla.json"])


def test_orca_with_profiles_takes_settings_from_them(no_slicers, monkeypatch, spaced_tmp, stl):
    exe = _install(spaced_tmp / "tools", "orca-slicer", FAKE_ORCA)
    monkeypatch.setenv("PIFORGE_SLICER", str(exe))
    profiles = ["--load-settings", "machine.json;process.json", "--load-filaments", "pla.json"]
    res = slice_stl(stl, "bambu_p1s", "PLA", spaced_tmp / "out", infill=0.4, extra_args=profiles)
    assert res.settings_applied is False  # the profiles decide, not infill=0.4
    argv = (exe.parent / "argv.txt").read_text().splitlines()
    assert argv[argv.index("--load-settings") + 1] == "machine.json;process.json"


def test_orca_never_returns_stale_plate_gcode(no_slicers, monkeypatch, spaced_tmp, stl):
    monkeypatch.setenv("PIFORGE_SLICER",
                       str(_install(spaced_tmp / "tools", "orca-slicer", FAKE_ORCA_SILENT)))
    out_dir = spaced_tmp / "out"
    out_dir.mkdir()
    (out_dir / "plate_1.gcode").write_text("; total estimated time: 9h 0m 0s\n"
                                           "; total filament weight [g] : 999\n")
    keep = out_dir / "notes.gcode"  # not a slicer output name: must survive untouched
    keep.write_text("; my notes\n")
    with pytest.raises(PiForgeError, match="no G-code"):
        slice_stl(stl, "bambu_p1s", "PLA", out_dir)
    assert not (out_dir / "plate_1.gcode").exists()  # stale output cleared before slicing
    assert keep.read_text() == "; my notes\n"


